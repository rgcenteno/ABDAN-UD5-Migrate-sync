-- =====================================================================
-- 02-destino-esquema.sql
-- Se ejecuta en Aurora PostgreSQL, base de datos ud5, como adminud5.
-- Crea las tablas y sus claves primarias ANTES de la carga. Las claves
-- ajenas, los índices secundarios y las restricciones UNIQUE se crean
-- después, con 03-destino-postcarga.sql.
-- Tipos: INT UNSIGNED -> BIGINT, TINYINT(1) -> SMALLINT, DATETIME -> TIMESTAMP(0).
-- =====================================================================
SET search_path TO ud5;

CREATE TABLE aux_countries (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_code  VARCHAR(2)   NOT NULL,
    country_name  VARCHAR(100) NOT NULL
);

CREATE TABLE aux_rol (
    id_rol         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rol            VARCHAR(255) NOT NULL,
    descripcion_en TEXT         NOT NULL,
    descripcion_es TEXT         NOT NULL,
    orden          INTEGER      NOT NULL,
    seccion_ini    VARCHAR(255) NOT NULL
);

CREATE TABLE aux_rol_trabajador (
    id_rol     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol VARCHAR(100) NOT NULL
);

CREATE TABLE categoria (
    id_categoria     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_categoria VARCHAR(50) NOT NULL,
    id_padre         INTEGER
);

CREATE TABLE log (
    id_log    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    operacion VARCHAR(50) NOT NULL,
    tabla     VARCHAR(50) NOT NULL,
    detalle   TEXT,
    PRIMARY KEY (id_log, operacion, tabla)
);

CREATE TABLE proveedor (
    cif        VARCHAR(9)   PRIMARY KEY,
    codigo     VARCHAR(10)  NOT NULL,
    nombre     VARCHAR(255) NOT NULL,
    direccion  VARCHAR(255) NOT NULL,
    website    VARCHAR(255) NOT NULL,
    email      VARCHAR(255) NOT NULL,
    telefono   VARCHAR(12),
    id_country BIGINT       NOT NULL
);

CREATE TABLE producto (
    id_producto  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo       VARCHAR(10)   NOT NULL,
    nombre       VARCHAR(255)  NOT NULL,
    descripcion  TEXT          NOT NULL,
    proveedor    VARCHAR(9)    NOT NULL,
    coste        NUMERIC(10,2) NOT NULL,
    margen       NUMERIC(10,2) NOT NULL,
    stock        INTEGER       NOT NULL,
    iva          INTEGER       NOT NULL,
    id_categoria INTEGER
);

CREATE TABLE trabajadores (
    username      VARCHAR(50)   PRIMARY KEY,
    salariobruto  NUMERIC(10,2) NOT NULL,
    retencionirpf NUMERIC(10,2) NOT NULL,
    activo        SMALLINT      NOT NULL DEFAULT 0,
    id_rol        INTEGER       NOT NULL DEFAULT 1,
    id_country    BIGINT        NOT NULL
);

CREATE TABLE usuario_sistema (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol     INTEGER      NOT NULL DEFAULT 1,
    email      VARCHAR(255) NOT NULL,
    pass       VARCHAR(255) NOT NULL,
    nombre     VARCHAR(255) NOT NULL,
    last_date  TIMESTAMP(0),
    idioma     CHAR(2)      NOT NULL DEFAULT 'es',
    baja       INTEGER      NOT NULL DEFAULT 0
);

-- DMS solo necesita manipular datos en las tablas del esquema ud5.
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES IN SCHEMA ud5 TO dms_target;
